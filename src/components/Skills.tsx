// ─── Icon renderer ────────────────────────────────────────────────────────────

function ToolIcon({ tool }: { tool: Tool }) {
  const base: CSSProperties = {
    width: 38,
    height: 38,
    borderRadius: 8,
    flexShrink: 0,
    display: "flex",
    alignItems: "center",
    justifyContent: "center",
    background: tool.bg,
  };

  if (tool.icon === "img") {
    return (
      <div style={base}>
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={tool.imgSrc}
          alt={tool.name}
          style={{
            maxWidth: "80%",
            maxHeight: "80%",
            objectFit: "contain",
            ...(tool.imgStyle ?? {}),
          }}
        />
      </div>
    );
  }

  if (tool.icon === "svg") {
    return (
      <div style={base}>
        <svg
          viewBox="0 0 24 24"
          style={{ width: 20, height: 20, fill: tool.color }}
          aria-hidden="true"
        >
          <path d={tool.svgPath} />
        </svg>
      </div>
    );
  }

  // abbrev fallback
  return (
    <div
      style={{
        ...base,
        color: tool.color,
        fontFamily: "var(--font-jetbrains), monospace",
        fontSize: "0.52rem",
        fontWeight: 700,
        letterSpacing: "-0.02em",
      }}
    >
      {tool.abbrev}
    </div>
  );
}

